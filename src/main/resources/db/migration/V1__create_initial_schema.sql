-- Initial schema: shops, tags, the shop <-> tag join table, and products.
-- Matches the @Entity classes in com.minishopify.model as of Sprint 1.
--
-- Never edit a migration that has already been merged to main: Flyway checksums it, and the
-- app on Azure will refuse to start. Add a new V<n>__<description>.sql file instead
-- (see CONTRIBUTING.md, "Changing the database schema").

create table shops (
    id          bigint generated by default as identity,
    name        varchar(255) not null,
    description varchar(255),
    primary key (id)
);

create table tags (
    id   bigint generated by default as identity,
    name varchar(100) not null,
    primary key (id),
    constraint uk_tags_name unique (name)
);

create table shop_tags (
    shop_id bigint not null,
    tag_id  bigint not null,
    primary key (shop_id, tag_id),
    constraint fk_shop_tags_shop foreign key (shop_id) references shops (id),
    constraint fk_shop_tags_tag foreign key (tag_id) references tags (id)
);

create table products (
    id          bigint generated by default as identity,
    shop_id     bigint not null,
    name        varchar(255) not null,
    description varchar(255),
    price       numeric(10, 2) not null,
    inventory   integer not null,
    primary key (id),
    constraint fk_products_shop foreign key (shop_id) references shops (id)
);
