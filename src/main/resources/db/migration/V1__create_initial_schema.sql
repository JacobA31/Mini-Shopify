-- Initial schema: shops, tags, the shop <-> tag join table, products, and customer orders.
-- Matches the @Entity classes in com.minishopify.model as of Sprint 2.
--
-- Never edit a migration that has already been merged to main: Flyway checksums it, and the
-- app on Azure will refuse to start. Add a new V<n>__<description>.sql file instead
-- (see CONTRIBUTING.md, "Changing the database schema").

create table shops (
    id          bigint generated by default as identity,
    name        varchar(255) not null,
    description varchar(255),
    primary key (id)
);

create table tags (
    id   bigint generated by default as identity,
    name varchar(100) not null,
    primary key (id),
    constraint uk_tags_name unique (name)
);

create table shop_tags (
    shop_id bigint not null,
    tag_id  bigint not null,
    primary key (shop_id, tag_id),
    constraint fk_shop_tags_shop foreign key (shop_id) references shops (id),
    constraint fk_shop_tags_tag foreign key (tag_id) references tags (id)
);

create table products (
    id          bigint generated by default as identity,
    shop_id     bigint not null,
    name        varchar(255) not null,
    description varchar(255),
    price       numeric(10, 2) not null,
    inventory   integer not null,
    -- Optimistic-locking counter (@Version), so two checkouts can't oversell the same stock.
    version            bigint,
    -- Optional product picture, stored in the database (null when there is no image).
    image              blob,
    image_content_type varchar(255),
    primary key (id),
    constraint fk_products_shop foreign key (shop_id) references shops (id)
);

create table customer_orders (
    id        bigint generated by default as identity,
    placed_at timestamp(6) not null,
    total     numeric(12, 2) not null,
    primary key (id)
);

create table order_lines (
    id                bigint generated by default as identity,
    customer_order_id bigint not null,
    product_id        bigint not null,
    quantity          integer not null,
    unit_price        numeric(10, 2) not null,
    primary key (id),
    constraint fk_order_lines_order foreign key (customer_order_id) references customer_orders (id),
    constraint fk_order_lines_product foreign key (product_id) references products (id)
);
